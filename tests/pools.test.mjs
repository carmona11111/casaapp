import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openStore} from '../server/store.mjs';
import {randomUUID} from 'node:crypto';
import {poolState,poolAction,available} from '../server/pools.mjs';
const directory=mkdtempSync(join(tmpdir(),'casa-pools-'));
const db=openStore(join(directory,'home.sqlite'));
test('Las tareas empiezan libres y sin asignación; solo quien las coge puede completarlas',()=>{
 const today='2026-10-19';
 const state=poolState(db,today);
 assert.equal(state.tasks.length,40);
 assert.equal(state.tasks.filter(t=>t.active&&t.claimed_by).length,0);
 for(const pool of ['daily','every3','weekly','occasional','monthly'])assert.ok(state.tasks.some(t=>t.active&&t.pool===pool),pool);
 const task=state.tasks.find(t=>t.id==='t1');
 assert.equal(task.available,true);
 assert.throws(()=>poolAction(db,{template_id:task.id,actor:'ivan',action:'complete'},today),/Coge primero/);
 poolAction(db,{template_id:task.id,actor:'ivan',action:'claim'},today);
 assert.equal(poolState(db,today).tasks.find(t=>t.id===task.id).claimed_by,'ivan');
 assert.throws(()=>poolAction(db,{template_id:task.id,actor:'person2',action:'claim'},today),/Otra persona/);
 assert.throws(()=>poolAction(db,{template_id:task.id,actor:'person2',action:'complete'},today),/Coge primero/);
 poolAction(db,{template_id:task.id,actor:'ivan',action:'complete'},today);
 const after=poolState(db,today).tasks.find(t=>t.id===task.id);
 assert.equal(after.available,false);
 assert.equal(after.claimed_by,null);
 assert.equal(after.last.person_id,'ivan');
 assert.equal(poolState(db,today).totals.find(t=>t.person_id==='ivan').points,task.points);
 assert.equal(poolState(db,today).week.points,task.points);
 assert.equal(poolState(db,today).week.count,1);
 assert.equal(poolState(db,'2026-10-26').week.points,0);
 assert.throws(()=>poolAction(db,{template_id:task.id,actor:'ivan',action:'claim'},today),/ya se hizo/);
 assert.equal(poolState(db,'2026-10-20').tasks.find(t=>t.id===task.id).available,true);
});
test('Las tareas nuevas tienen habitación, XP propios y la compra conserva responsable',()=>{
 const tasks=poolState(db,'2026-10-19').tasks;
 const litter=tasks.find(t=>t.id==='default-litter-clean');
 assert.equal(litter.zone,'Salón y comedor');
 assert.equal(litter.pool,'every3');
 assert.equal(litter.points,10);
 assert.equal(available({pool:'monthly'},{local_date:'2026-10-31'},'2026-11-01'),true);
 assert.equal(available({pool:'monthly'},{local_date:'2026-10-01'},'2026-10-31'),false);
 poolAction(db,{template_id:'default-shopping-task',actor:'ivan',action:'claim'},'2026-10-19');
 assert.equal(poolState(db,'2026-10-20').tasks.find(t=>t.id==='default-shopping-task').claimed_by,'ivan');
 poolAction(db,{template_id:'default-shopping-task',actor:'ivan',action:'release'},'2026-10-20');
});
test('Los ciclos de 3 días y las semanas se desbloquean según la fecha',()=>{
 const every3={pool:'every3'},weekly={pool:'weekly'},occasional={pool:'occasional'};
 assert.equal(available(every3,{local_date:'2026-10-19'},'2026-10-21'),false);
 assert.equal(available(every3,{local_date:'2026-10-19'},'2026-10-22'),true);
 assert.equal(available(weekly,{local_date:'2026-10-19'},'2026-10-25'),false);
 assert.equal(available(weekly,{local_date:'2026-10-19'},'2026-10-26'),true);
 assert.equal(available(occasional,{local_date:'2026-10-19'},'2026-11-15'),false);
 assert.equal(available(occasional,{local_date:'2026-10-19'},'2026-11-16'),true);
});
test('Devolver una tarea la deja libre para otra persona',()=>{
 poolAction(db,{template_id:'t2',actor:'ivan',action:'claim'},'2026-10-19');
 poolAction(db,{template_id:'t2',actor:'ivan',action:'release'},'2026-10-19');
 poolAction(db,{template_id:'t2',actor:'person2',action:'claim'},'2026-10-19');
 assert.equal(poolState(db,'2026-10-19').tasks.find(t=>t.id==='t2').claimed_by,'person2');
 assert.equal(poolState(db,'2026-10-20').tasks.find(t=>t.id==='t2').claimed_by,null);
});
test('Reiniciar el marcador conserva el historial y cuenta solo acciones posteriores',()=>{
 const prior=db.prepare('SELECT COUNT(*) AS n FROM task_completions').get().n;
 assert.ok(prior>0);
 const epoch=new Date(Date.now()+1000).toISOString();
 db.prepare('UPDATE score_epoch SET started_at=? WHERE id=1').run(epoch);
 const cleared=poolState(db,'2026-10-19');
 assert.equal(cleared.totals.reduce((sum,row)=>sum+row.points,0),0);
 assert.equal(cleared.week.points,0);
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM task_completions').get().n,prior);
 db.prepare('INSERT INTO task_completions VALUES (?,?,?,?,?,?,?,?,?)').run(randomUUID(),'t3','ivan',new Date(Date.now()+2000).toISOString(),'2026-10-19','2026-10-19',10,'Gesto nuevo','Cocina');
 assert.equal(poolState(db,'2026-10-19').totals.find(row=>row.person_id==='ivan').points,10);
});
process.on('exit',()=>{db.close();rmSync(directory,{recursive:true,force:true});});
